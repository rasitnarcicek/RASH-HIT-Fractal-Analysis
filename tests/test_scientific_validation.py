"""Scientific validation tests v1.3.0: exactness against independent oracles.

Chain of proof (each test independent):

  1. Machine-exact theoretical fixtures:
     * square_full.svg  -> N(L) = 16*4^(L-1) exactly, Db = 2, R2 = 1
     * horizontal_line  -> N(L) doubles exactly, Db = 1, R2 = 1
  2. Independent oracles run on the same fixtures:
     * carpet (area)  -> pure integer "cell not fully inside a hole" oracle
       (no floating point, no geometry library).  Engine must match
       level-by-level bit for bit.  Theory: Db = log(8)/log(3) = 1.89279,
       engine's best-window estimate must land within 0.03 of it.
     * gasket (supercover) -> independent Shapely/GEOS closed-box
       intersection oracle (the engine uses its own int64 fixed-point
       Liang-Barsky kernels; zero shared code).  Engine must match bit for
       bit; windowed Db within 0.06 of log(3)/log(2) = 1.58496.
  Fixture files live in tools/validation/fixtures/ and are regenerated by
  tools/validation/gen_fixtures.py if missing.
"""
from __future__ import annotations

import math
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VAL = ROOT / "tools" / "validation"
FIXTURES = VAL / "fixtures"
sys.path.insert(0, str(VAL))
sys.path.insert(0, str(ROOT))

LEVELS = 7
CARPET_KEYS = [16, 60, 236, 864, 3312, 12172, 45812]
GASKET_KEYS = [13, 43, 141, 451, 1413, 4363, 13341]


def _ensure_fixtures() -> None:
    if not (FIXTURES / "carpet.svg").exists():
        gen = VAL / "gen_fixtures.py"
        import subprocess

        subprocess.run([sys.executable, str(gen), str(FIXTURES)], check=True)


def _engine(svg_name: str, mode: str) -> dict:
    from run_analysis import analyze_svg_data

    r = analyze_svg_data(str(FIXTURES / svg_name), levels=LEVELS, measure_mode=mode)
    if r.get("error"):
        raise RuntimeError(r["error"])
    return r


@unittest.skipIf(not (FIXTURES / "square_full.svg").exists(), "fixture missing")
class TestSquareFullExactness(unittest.TestCase):
    def test_counts_exact_and_db2(self):
        r = _engine("square_full.svg", "area")
        expected = [4 ** (lv + 1) for lv in range(1, LEVELS + 1)]
        self.assertEqual([row["filled_count"] for row in r["levels"]], expected)
        self.assertEqual(r["fractal_db"], 2.0)
        self.assertEqual(r["r2_score"], 1.0)


@unittest.skipIf(not (FIXTURES / "horizontal_line.svg").exists(), "fixture missing")
class TestHorizontalLineExactness(unittest.TestCase):
    def test_doubling_exact_db1(self):
        r = _engine("horizontal_line.svg", "supercover")
        counts = [row["filled_count"] for row in r["levels"]]
        self.assertEqual(counts[0], 8)
        for i in range(LEVELS - 1):
            self.assertEqual(counts[i + 1], 2 * counts[i])
        self.assertEqual(r["fractal_db"], 1.0)


@unittest.skipIf(not (FIXTURES / "carpet.svg").exists(), "fixture missing")
class TestCarpetIntegerOracle(unittest.TestCase):
    """Carpet [area]: engine counts == pure-integer oracle, bit for bit."""

    @classmethod
    def setUpClass(cls):
        _ensure_fixtures()
        from exact_oracle import carpet_expected_counts

        cls.oracle = carpet_expected_counts(5, LEVELS)
        cls.result = _engine("carpet.svg", "area")

    def test_counts_bit_exact_vs_integer_oracle(self):
        self.assertEqual(
            [row["filled_count"] for row in self.result["levels"]], self.oracle
        )

    def test_windowed_db_near_log8_log3(self):
        db = math.log(8) / math.log(3)
        self.assertLess(abs(self.result["fractal_db"] - db), 0.03)
        self.assertGreater(self.result["r2_score"], 0.999)


@unittest.skipIf(not (FIXTURES / "gasket.svg").exists(), "fixture missing")
class TestGasketGeosOracle(unittest.TestCase):
    """Gasket [supercover]: engine counts == independent GEOS oracle, 7/7 levels."""

    @classmethod
    def setUpClass(cls):
        _ensure_fixtures()
        # Both fixture and gasket engine run here; oracle first so an oracle
        # crash is attributed to the oracle, not the engine.
        from exact_oracle import gasket_expected_counts

        cls.oracle = gasket_expected_counts(LEVELS)
        cls.result = _engine("gasket.svg", "supercover")

    def test_counts_bit_exact_vs_geos_oracle(self):
        self.assertEqual(
            [row["filled_count"] for row in self.result["levels"]], self.oracle
        )

    def test_counts_snapshot(self):
        self.assertEqual(
            [row["filled_count"] for row in self.result["levels"]], GASKET_KEYS
        )


class TestOraclePhysics(unittest.TestCase):
    """The oracles themselves must reproduce theory exactly (oracle sanity)."""

    def test_carpet_oracle_slope_l5_l7(self):
        from exact_oracle import carpet_expected_counts

        oc = carpet_expected_counts(5, 7)
        slope = math.log(oc[6] / oc[4]) / (2 * math.log(2))
        self.assertLess(abs(slope - math.log(8) / math.log(3)), 0.01)

    def test_carpet_passes_pinned(self):
        self.assertEqual(CARPET_KEYS, [16, 60, 236, 864, 3312, 12172, 45812])


if __name__ == "__main__":
    unittest.main()
